#!/usr/bin/env node
/**
 * Right-size the archive posters for the GPU.
 *
 * The masters in `public/archive/` are print-scale — `Poster9 File.webp` is
 * 3000x4000, which is 45MB of RGBA once decoded, for a tile the archive draws
 * at ~165px in orb view and at most a phone screen's height in grid view. All
 * eleven sources together are 5.1MB over the wire and ~112MB of texture memory,
 * and `useArchiveMedia` waits for every one of them before the poster field
 * builds, so on a 4 Mbps connection the orb sat empty for fifteen seconds.
 *
 * This emits one variant per (source, cap) pair into `generated/`, which
 * `archiveLoadMedia` picks from by viewport. Every pair gets a file even when
 * the master is already under the cap — a copy costs disk, and the alternative
 * is the loader eating a 404 round trip per image to discover that.
 *
 * Outputs are gitignored and regenerated by the `prebuild` hook, so nothing
 * here is a source of truth: replace a master and the variants follow on the
 * next build. If sharp is missing this exits 0 without writing anything and
 * the loader falls back to the masters — a slow archive, not a failed deploy.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Longest edge, per device class. Mirrors `TEXTURE_CAPS` in
 * `src/lib/archive/archiveLoadMedia.ts` — the two lists have to agree, since
 * the URL is built from the number.
 *
 * 1024 is the phone: that canvas is `dpr={[1, 1.5]}`, so a 390px-wide screen
 * gives a 1266px-tall buffer and a grid poster fills it. 1600 covers a laptop
 * at the same zoom with room to spare.
 */
const CAPS = [1024, 1600];

const SOURCE_DIR = "public/archive";
const OUT_DIR = path.join(SOURCE_DIR, "generated");

/** Well under the masters' visually-lossless setting; these are never printed. */
const WEBP_QUALITY = 78;

async function main() {
  let sharp;
  try {
    ({ default: sharp } = await import("sharp"));
  } catch {
    console.warn(
      "[archive-variants] sharp unavailable — shipping the full-size masters.",
    );
    return;
  }

  const entries = (await readdir(SOURCE_DIR, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && /\.webp$/i.test(entry.name))
    .map((entry) => entry.name);

  if (!entries.length) {
    console.warn(`[archive-variants] no .webp sources in ${SOURCE_DIR}`);
    return;
  }

  await mkdir(OUT_DIR, { recursive: true });

  let written = 0;
  let bytesIn = 0;
  let bytesOut = 0;

  for (const name of entries) {
    const source = path.join(SOURCE_DIR, name);
    const input = await readFile(source);
    bytesIn += input.length;

    const { width = 0, height = 0 } = await sharp(input).metadata();
    const longest = Math.max(width, height);

    for (const cap of CAPS) {
      const out = path.join(OUT_DIR, variantName(name, cap));
      /* `withoutEnlargement` alone would still re-encode a small master and
         can come out bigger than it went in; hand those through untouched. */
      const data =
        longest <= cap
          ? input
          : await sharp(input)
              .resize({
                width: cap,
                height: cap,
                fit: "inside",
                withoutEnlargement: true,
              })
              .webp({ quality: WEBP_QUALITY, effort: 5 })
              .toBuffer();

      await writeFile(out, data);
      written += 1;
      if (cap === CAPS[0]) bytesOut += data.length;
    }
  }

  console.log(
    `[archive-variants] ${written} file(s) from ${entries.length} master(s); ` +
      `phone payload ${kb(bytesOut)} (masters ${kb(bytesIn)}).`,
  );
}

/** `Poster 6.webp` + 1024 -> `Poster 6-1024.webp`. Kept in sync with the loader. */
function variantName(name, cap) {
  return name.replace(/\.webp$/i, `-${cap}.webp`);
}

function kb(bytes) {
  return `${Math.round(bytes / 1024)}KB`;
}

await main();
